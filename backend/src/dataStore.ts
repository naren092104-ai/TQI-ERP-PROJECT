// In-memory data store instance
let db: DataStore = { ...initialData };

// Load from disk if exists
export function initDataStore() {
  try {
    if (fs.existsSync(DATA_FILE)) {
      const raw = fs.readFileSync(DATA_FILE, 'utf-8');
      const loaded = JSON.parse(raw);
      db = {
        ...initialData,
        ...loaded,
        users: loaded.users || initialData.users,
        clusters: loaded.clusters || initialData.clusters,
        panchayats: loaded.panchayats || initialData.panchayats,
        students: loaded.students || initialData.students,
        volunteers: loaded.volunteers || initialData.volunteers,
        sessions: loaded.sessions || initialData.sessions,
        attendanceSessions: loaded.attendanceSessions || initialData.attendanceSessions,
        lessonPlans: loaded.lessonPlans || initialData.lessonPlans,
        financeEntries: loaded.financeEntries || initialData.financeEntries,
        financeDrafts: loaded.financeDrafts || initialData.financeDrafts,
        correctionRequests: loaded.correctionRequests || initialData.correctionRequests,
        approvals: loaded.approvals || initialData.approvals,
        auditLogs: loaded.auditLogs || initialData.auditLogs,
        notifications: loaded.notifications || initialData.notifications,
      };
      console.log('✅ TQI Database loaded from persistence disk.');
    } else {
      saveDataStore();
      console.log('✅ TQI Database initialized with seeded relations.');
    }
  } catch (err) {
    console.error('Error initializing DataStore:', err);
    db = { ...initialData };
  }
}

export function saveDataStore() {
  try {
    fs.writeFileSync(DATA_FILE, JSON.stringify(db, null, 2), 'utf-8');
  } catch (err) {
    console.error('Error saving DataStore to disk:', err);
  }
}

export function getDB(): DataStore {
  return db;
}

// Add an audit log entry automatically whenever state changes
export function addAuditLog(entry: Omit<AuditLogEntry, 'id' | 'timestamp'>) {
  const newLog: AuditLogEntry = {
    id: `aud-${Date.now()}-${Math.round(Math.random() * 1000)}`,
    timestamp: new Date().toISOString().replace('T', ' ').substring(0, 19),
    ...entry,
  };
  db.auditLogs.unshift(newLog);
  if (db.auditLogs.length > 500) {
    db.auditLogs.pop();
  }
  saveDataStore();
  return newLog;
}

// Add notification helper
export function addNotification(notif: Omit<NotificationItem, 'id' | 'timeAgo'>) {
  const newNotif: NotificationItem = {
    id: `notif-${Date.now()}-${Math.round(Math.random() * 1000)}`,
    timeAgo: 'Just now',
    ...notif,
  };
  db.notifications.unshift(newNotif);
  if (db.notifications.length > 100) {
    db.notifications.pop();
  }
  saveDataStore();
  return newNotif;
}
